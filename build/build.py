#!/usr/bin/env python3
"""Build pipeline for the System Design Knowledge Base.

Single source of truth: manuscript/**/*.md. This script:
  1. extracts every Mermaid block, saves its source to diagrams/chNN/, and renders SVG + PNG
     (cached by content hash) with headless Chromium;
  2. generates the diagram collection (Appendix D) and formula handbook (Appendix C);
  3. assembles each deliverable volume listed in build/book.yaml;
  4. converts each volume to standalone HTML (pandoc), PDF (Chromium) and DOCX (pandoc).

Usage:
  python3 build/build.py                      # all volumes, all formats
  python3 build/build.py --volume D1-system-design-textbook --formats html,pdf
  python3 build/build.py --chapters 1-10 --name preview
"""
import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
MANUSCRIPT = ROOT / "manuscript"
DIST = ROOT / "dist"
DIAGRAMS = ROOT / "diagrams"
CACHE = BUILD / ".cache" / "diagrams"
CSS = BUILD / "styles" / "book.css"
REFERENCE_DOCX = BUILD / "styles" / "reference.docx"
DOCX_FILTER = BUILD / "filters" / "docx-callouts.lua"

MERMAID_RE = re.compile(r"^```mermaid[ \t]*\n(.*?)^```[ \t]*$", re.S | re.M)
FIGURE_RE = re.compile(r"\*\*Figure\s+([0-9A-Z]+\.[0-9]+)\s*[—–-]\s*(.+?)\*\*")
CALLOUT_RE = re.compile(r"^:::\s*\{?\.?(formula)\}?\s*$\n(.*?)^:::\s*$", re.S | re.M)


def load_manifest():
    return yaml.safe_load((BUILD / "book.yaml").read_text())


def chapter_files(num, book):
    folder = MANUSCRIPT / book
    return sorted(folder.glob(f"{num:02d}-*.md")) + sorted(folder.glob(f"{num:02d}[a-z]-*.md"))


# ---------------------------------------------------------------- diagrams
def collect_diagrams(chapters):
    """Return {chapter_num: [(hash, code, figure_label, caption)]} and write .mmd sources."""
    found = {}
    for num, files in chapters:
        items = []
        for f in files:
            text = f.read_text()
            for m in MERMAID_RE.finditer(text):
                code = m.group(1)
                before = text[max(0, m.start() - 600):m.start()]
                caps = FIGURE_RE.findall(before)
                label, caption = caps[-1] if caps else (f"{num}.?", "Untitled diagram")
                h = hashlib.sha1(code.encode()).hexdigest()[:12]
                items.append((h, code, label, caption.strip().rstrip(".")))
        found[num] = items
        if items:
            out = DIAGRAMS / f"ch{num:02d}"
            out.mkdir(parents=True, exist_ok=True)
            for old in out.glob("*.mmd"):
                old.unlink()
            for i, (h, code, label, caption) in enumerate(items, 1):
                (out / f"fig-{num:02d}-{i:02d}.mmd").write_text(f"%% Figure {label} — {caption}\n{code}")
    return found


def render_diagrams(found):
    jobs = []
    for items in found.values():
        for h, code, _, _ in items:
            if not (CACHE / f"{h}.svg").exists() and not any(j["id"] == h for j in jobs):
                jobs.append({"id": h, "code": code, "out": str(CACHE)})
    if not jobs:
        return {}
    CACHE.mkdir(parents=True, exist_ok=True)
    print(f"  rendering {len(jobs)} new diagram(s)…", flush=True)
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as tf:
        json.dump(jobs, tf)
    res = subprocess.run(["node", str(BUILD / "render_mermaid.js"), tf.name], capture_output=True, text=True, cwd=BUILD)
    if res.returncode != 0:
        sys.exit(f"mermaid renderer failed:\n{res.stderr[-2000:]}")
    errors = {r["id"]: r["error"] for r in json.loads(res.stdout) if not r["ok"]}
    for h, err in errors.items():
        print(f"  ! diagram {h} failed: {err}")
    return errors


def replace_mermaid(text, fmt):
    def sub(m):
        h = hashlib.sha1(m.group(1).encode()).hexdigest()[:12]
        img = CACHE / f"{h}.{'png' if fmt == 'docx' else 'svg'}"
        if not img.exists():
            return "::: warning\n**Diagram failed to render.** Source:\n\n```text\n" + m.group(1) + "```\n:::"
        return f"![]({img}){{.diagram}}"
    return MERMAID_RE.sub(sub, text)


# ---------------------------------------------------------------- generated appendices
def generate_diagram_collection(found, titles):
    lines = ["# Appendix D — Architecture Diagram Collection", "",
             "> Generated by `build/build.py` from every Mermaid diagram in the manuscript. "
             "Sources are in `diagrams/chNN/*.mmd`. Each figure links back to the chapter that explains it.", ""]
    for num, items in sorted(found.items()):
        if not items:
            continue
        lines += [f"## Chapter {num} — {titles[num]}", ""]
        for h, code, label, caption in items:
            lines += [f"**Figure {label} — {caption}.**", "", "```mermaid", code.rstrip("\n"), "```", ""]
    out = MANUSCRIPT / "appendices" / "D-diagram-collection.md"
    out.write_text("\n".join(lines))
    return out


def generate_formula_handbook(chapters, titles):
    lines = ["# Appendix C — Formula and Quantitative Estimation Handbook", "",
             "> Generated by `build/build.py` from every `formula` callout in the manuscript, "
             "grouped by chapter. Worked examples remain in the chapters; follow the section reference.", ""]
    for num, files in chapters:
        blocks = []
        for f in files:
            text = f.read_text()
            for m in CALLOUT_RE.finditer(text):
                head = text[:m.start()]
                secs = re.findall(r"^#{2,3}\s+(\d+\.\d+(?:\.\d+)?)\s", head, re.M)
                blocks.append((secs[-1] if secs else str(num), m.group(2).rstrip()))
        if blocks:
            lines += [f"## Chapter {num} — {titles[num]}", ""]
            for sec, body in blocks:
                lines += [f"*From §{sec}*", "", "::: formula", body, ":::", ""]
    out = MANUSCRIPT / "appendices" / "C-formula-handbook.md"
    out.write_text("\n".join(lines))
    return out


def generate_glossary(chapters, titles):
    """Appendix A: every `definition` callout of the form **Definition — Term.** text."""
    entries = {}
    pat = re.compile(r"^:::\s*\{?\.?definition\}?\s*$\n(.*?)^:::\s*$", re.S | re.M)
    for num, files in chapters:
        for f in files:
            text = f.read_text()
            for m in pat.finditer(text):
                body = " ".join(m.group(1).split())
                dm = re.match(r"\*\*Definition\s*[—–-]\s*(.+?)\.?\*\*\s*(.*)", body)
                if not dm:
                    continue
                term, desc = dm.group(1).strip().rstrip("."), dm.group(2).strip()
                secs = re.findall(r"^#{2,3}\s+(\d+\.\d+(?:\.\d+)?)\s", text[:m.start()], re.M)
                key = term.lower()
                if key not in entries:
                    entries[key] = (term, desc, secs[-1] if secs else str(num))
    lines = ["# Appendix A — Glossary", "",
             "> Generated by `build/build.py` from the definition callouts in every chapter; the first (defining) "
             "occurrence of each term is used. Canonical usage rules are in `docs/project/terminology.md`.", ""]
    letter = None
    for key in sorted(entries, key=lambda k: re.sub(r"[^a-z0-9]", "", k)):
        term, desc, sec = entries[key]
        first = (re.sub(r"[^A-Za-z0-9]", "", term)[:1] or "#").upper()
        if first != letter:
            letter = first
            lines += [f"## {letter}", ""]
        lines += [f"**{term}** — {desc} *(§{sec})*", ""]
    out = MANUSCRIPT / "appendices" / "A-glossary.md"
    out.write_text("\n".join(lines))
    return out


# ---------------------------------------------------------------- assembly
def title_block(title, subtitle, n_chapters):
    return (f'<div class="title-page"><h1 class="title">{title}</h1>'
            f'<p class="subtitle">{subtitle}</p>'
            f'<p class="meta">Built from the manuscript sources · {n_chapters} chapter(s) in this edition</p></div>\n')


def assemble(name, title, nums, manifest, extra_files=()):
    chapters = {c[0]: c for c in manifest["chapters"]}
    parts = {p[0]: p[1] for p in manifest["parts"]}
    body, included = [], []
    for n in nums:
        files = chapter_files(n, chapters[n][3])
        if not files:
            continue
        if n in parts:
            body.append(f'\n# {parts[n]} {{.part-title .unnumbered}}\n')
        for f in files:
            body.append(f.read_text())
        included.append(n)
    for f in extra_files:
        if Path(f).exists():
            body.append(Path(f).read_text())
    return included, "\n\n".join(body)


def pandoc_html(md_text, out_html, title):
    with tempfile.TemporaryDirectory() as td:
        src = Path(td) / "book.md"
        src.write_text(md_text)
        before = Path(td) / "before.html"
        before.write_text(title_block(title, "From first principles to expert practice", md_text.count("\n# Chapter")))
        subprocess.run([
            "pandoc", str(src), "-f", "markdown-implicit_figures+fenced_divs+pipe_tables+tex_math_dollars",
            "-t", "html5", "-s", "--toc", "--toc-depth=2", "--mathml", "--embed-resources",
            "--highlight-style=tango", f"--css={CSS}", f"--include-before-body={before}",
            "--metadata", f"title={title}", "--metadata", "lang=en",
            "--variable", "title-block=false", "-o", str(out_html),
        ], check=True)
    # pandoc emits its own title header; hide it since the title page replaces it
    html = out_html.read_text().replace('<header id="title-block-header">', '<header id="title-block-header" hidden>')
    out_html.write_text(html)


def pandoc_docx(md_text, out_docx, title):
    if not REFERENCE_DOCX.exists():
        subprocess.run([sys.executable, str(BUILD / "make_reference_docx.py")], check=True)
    with tempfile.TemporaryDirectory() as td:
        src = Path(td) / "book.md"
        src.write_text(md_text)
        subprocess.run([
            "pandoc", str(src), "-f", "markdown-implicit_figures+fenced_divs+pipe_tables+tex_math_dollars",
            "-t", "docx", "--toc", "--toc-depth=2", f"--reference-doc={REFERENCE_DOCX}",
            f"--lua-filter={DOCX_FILTER}", "--highlight-style=tango",
            "--metadata", f"title={title}", "-o", str(out_docx),
        ], check=True)


def pdf_from_html(html, pdf, title):
    subprocess.run(["node", str(BUILD / "print_pdf.js"), str(html), str(pdf), title], check=True, cwd=BUILD)


def build_volume(name, title, nums, manifest, formats, extra=()):
    included, md = assemble(name, title, nums, manifest, extra)
    if not included and not (extra and nums == []):
        print(f"- {name}: no chapters written yet, skipped")
        return
    print(f"- {name}: chapters {included}")
    DIST.mkdir(exist_ok=True)
    if "html" in formats or "pdf" in formats:
        html = DIST / f"{name}.html"
        pandoc_html(replace_mermaid(md, "html"), html, title)
        if "pdf" in formats:
            pdf_from_html(html, DIST / f"{name}.pdf", title)
        if "html" not in formats:
            html.unlink()
    if "docx" in formats:
        pandoc_docx(replace_mermaid(md, "docx"), DIST / f"{name}.docx", title)


def parse_range(s):
    out = []
    for part in s.split(","):
        a, _, b = part.partition("-")
        out += list(range(int(a), int(b or a) + 1))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--volume", help="volume key from book.yaml (default: all)")
    ap.add_argument("--chapters", help="ad-hoc chapter range, e.g. 1-10 (builds a preview volume)")
    ap.add_argument("--name", default="preview", help="output name for --chapters builds")
    ap.add_argument("--formats", default="html,pdf,docx")
    args = ap.parse_args()
    formats = set(args.formats.split(","))

    manifest = load_manifest()
    titles = {c[0]: c[2] for c in manifest["chapters"]}
    all_chapters = [(c[0], chapter_files(c[0], c[3])) for c in manifest["chapters"]]
    all_chapters = [(n, fs) for n, fs in all_chapters if fs]

    print("Diagrams:")
    found = collect_diagrams(all_chapters)
    errors = render_diagrams(found)
    print(f"  {sum(len(v) for v in found.values())} diagram(s) across {len(all_chapters)} chapter(s); {len(errors)} error(s)")
    appendix_d = generate_diagram_collection(found, titles)
    appendix_c = generate_formula_handbook(all_chapters, titles)
    generate_glossary(all_chapters, titles)

    print("Volumes:")
    if args.chapters:
        nums = parse_range(args.chapters)
        build_volume(args.name, "The Complete System Design Knowledge Base — Preview", nums, manifest, formats)
        return
    for key, vol in manifest["volumes"].items():
        if args.volume and key != args.volume:
            continue
        lo, hi = vol["chapters"] or (0, -1)
        nums = sorted((set(vol.get("include", [])) | set(range(lo, hi + 1))) - set(vol.get("exclude", [])))
        extra = [ROOT / e for e in vol.get("extra", [])]
        chapters_by_num = {c[0]: c for c in manifest["chapters"]}
        if hi >= lo and not any(chapter_files(n, chapters_by_num[n][3]) for n in range(lo, hi + 1)):
            print(f"- {key}: none of chapters {lo}-{hi} written yet, skipped")
            continue
        build_volume(key, vol["title"], nums, manifest, formats, extra=extra)
    if not args.volume or args.volume.startswith("D4"):
        build_volume("D4-architecture-diagram-collection", "Architecture Diagram Collection", [], manifest,
                     formats - {"docx"}, extra=[appendix_d])
    if not args.volume or args.volume.startswith("D5"):
        build_volume("D5-formula-handbook", "Formula and Quantitative Estimation Handbook", [], manifest,
                     formats, extra=[appendix_c])


if __name__ == "__main__":
    main()
